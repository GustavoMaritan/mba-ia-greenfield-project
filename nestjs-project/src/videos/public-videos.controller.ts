import { Controller, Get, Param, Res } from '@nestjs/common';
import {
  ApiOperation,
  ApiParam,
  ApiResponse,
  ApiTags,
  getSchemaPath,
} from '@nestjs/swagger';
import { SkipThrottle } from '@nestjs/throttler';
import type { Response } from 'express';
import { Public } from '../auth/decorators/public.decorator';
import { ApiErrorEnvelope } from '../common/openapi/api-error-envelope.dto';
import {
  PublicVideoResponseDto,
  toPublicVideoResponse,
} from './dto/public-video-response.dto';
import { VideosService } from './videos.service';

const errorSchema = { $ref: getSchemaPath(ApiErrorEnvelope) };
const notFound = {
  status: 404,
  description: 'Unknown public id or video not ready',
  schema: errorSchema,
};
const redirect = (description: string) => ({
  status: 302,
  description,
  headers: {
    Location: {
      description: 'Presigned storage URL (expires in 1 hour)',
      schema: { type: 'string', format: 'uri' },
    },
  },
});

// URL assinada expira em 1h: o redirect não pode ficar em cache
function redirectNoStore(res: Response, url: string): void {
  res.setHeader('Cache-Control', 'no-store');
  res.redirect(302, url);
}

@ApiTags('videos')
@Public()
@SkipThrottle()
@Controller('videos')
export class PublicVideosController {
  constructor(private readonly videosService: VideosService) {}

  @Get(':publicId')
  @ApiOperation({
    summary: 'Get a public video',
    description:
      'Anonymous access to a ready video: details plus the stream, download and thumbnail routes.',
  })
  @ApiParam({ name: 'publicId', description: '11-char public id' })
  @ApiResponse({ status: 200, type: PublicVideoResponseDto })
  @ApiResponse(notFound)
  async findOne(
    @Param('publicId') publicId: string,
  ): Promise<PublicVideoResponseDto> {
    return toPublicVideoResponse(
      await this.videosService.findReadyByPublicId(publicId),
    );
  }

  @Get(':publicId/stream')
  @ApiOperation({
    summary: 'Stream a video',
    description:
      'Redirects to a presigned storage URL; storage answers HTTP Range requests with 206 Partial Content, so playback starts without downloading the whole file.',
  })
  @ApiParam({ name: 'publicId', description: '11-char public id' })
  @ApiResponse(redirect('Redirect to the streamable object'))
  @ApiResponse(notFound)
  async stream(
    @Param('publicId') publicId: string,
    @Res() res: Response,
  ): Promise<void> {
    redirectNoStore(res, await this.videosService.getStreamUrl(publicId));
  }

  @Get(':publicId/download')
  @ApiOperation({
    summary: 'Download a video',
    description:
      'Redirects to a presigned storage URL that answers with Content-Disposition: attachment and the original file name.',
  })
  @ApiParam({ name: 'publicId', description: '11-char public id' })
  @ApiResponse(redirect('Redirect to the downloadable object'))
  @ApiResponse(notFound)
  async download(
    @Param('publicId') publicId: string,
    @Res() res: Response,
  ): Promise<void> {
    redirectNoStore(res, await this.videosService.getDownloadUrl(publicId));
  }

  @Get(':publicId/thumbnail')
  @ApiOperation({
    summary: 'Get a video thumbnail',
    description:
      'Redirects to a presigned storage URL of the JPEG frame generated by the worker.',
  })
  @ApiParam({ name: 'publicId', description: '11-char public id' })
  @ApiResponse(redirect('Redirect to the thumbnail image'))
  @ApiResponse(notFound)
  async thumbnail(
    @Param('publicId') publicId: string,
    @Res() res: Response,
  ): Promise<void> {
    redirectNoStore(res, await this.videosService.getThumbnailUrl(publicId));
  }
}
